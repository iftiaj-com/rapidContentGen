/* ============================================================================
 * ORIGAMI EFFECT
 * ----------------------------------------------------------------------------
 *  Three rendering modes share one panel:
 *   • "crumple"  → photoreal crumpled-paper engine (procedural mesh, depth
 *                  sorting, flat-shaded lighting, paper grain, 3D tumble).
 *                  Uses the FULL media aspect ratio.
 *   • "sculpt"   → folded-photo portrait sculpture (editorial 3/4 bust):
 *                  gentle dome + anatomy-scale facets, per-section photo
 *                  misalignment, muted color — the "folded photo face" look.
 *   • "paperball"→ the same crumple engine wrapped onto a sphere — a tight,
 *                  faceted ball of paper (square, with a soft contact shadow).
 *   • "football" → wraps the MEDIA onto a truncated-icosahedron soccer ball
 *                  (12 pentagon + 20 hexagon panels), flat-shaded with seams.
 *   • "flower"   → wraps the MEDIA onto a procedural 3-D bloom (concentric
 *                  whorls of curved petals); fold drives bud → open flower.
 *   • "mandala"  → 3-D mandala wind spinner: concentric scalloped rings that
 *                  separate in depth and spin independently (audio-driven).
 *   • presets    → hand-authored fold meshes (bird, crane, cat, fox, heart…)
 *                  rendered square with affine texture warping + color modes.
 *
 *  Fold (0 → 1) drives the transformation: flat sheet → folded/crumpled form.
 *  At fold = 0 the media is shown flat with crease lines only — no motion.
 * ========================================================================== */

